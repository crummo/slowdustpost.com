// Gives each project in <site>/work-data.js its own page at <site>/work/<slug>/index.html, so a
// shared link unfurls with that project's title and thumbnail. Each page is the site's index.html
// with its meta block swapped and a <base> back to the site root; player.js opens the video on load.
//
//   node scripts/build-work-pages.mjs        # builds v2/work/*
//   node scripts/build-work-pages.mjs .      # once v2 is the live site at the root
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import vm from 'node:vm';

const SITE_URL = 'https://slowdustpost.com';
const siteDir = resolve(process.argv[2] ?? 'v2');

const sandbox = { window: {} };
vm.runInNewContext(readFileSync(join(siteDir, 'work-data.js'), 'utf8'), sandbox);
const work = sandbox.window.SLOWDUST_WORK;

const template = readFileSync(join(siteDir, 'index.html'), 'utf8');
const META = /<!-- meta:start[\s\S]*?<!-- meta:end -->/;
if (!META.test(template)) throw new Error('index.html is missing its <!-- meta:start --> … <!-- meta:end --> block');

const esc = (s) => String(s)
  .replace(/&/g, '&amp;')
  .replace(/</g, '&lt;')
  .replace(/>/g, '&gt;')
  .replace(/"/g, '&quot;');

const outDir = join(siteDir, 'work');
rmSync(outDir, { recursive: true, force: true });

for (const w of work) {
  const name = `${w.client} — ${w.title}`;
  const url = `${SITE_URL}/work/${w.slug}/`;
  const meta = `<base href="../../">
  <title>${esc(name)} — Slowdust Post</title>
  <meta name="description" content="${esc(`${name}. ${w.kind}. Post production by Slowdust Post, Los Angeles.`)}">
  <link rel="canonical" href="${url}">
  <meta property="og:type" content="video.other">
  <meta property="og:site_name" content="Slowdust Post">
  <meta property="og:title" content="${esc(name)}">
  <meta property="og:description" content="${esc(`${w.kind} · Slowdust Post, Los Angeles`)}">
  <meta property="og:url" content="${url}">
  <meta property="og:image" content="${esc(w.thumb)}">
  <meta property="og:image:alt" content="${esc(w.title)}">
  <meta name="twitter:card" content="summary_large_image">
  <meta name="twitter:title" content="${esc(name)}">
  <meta name="twitter:image" content="${esc(w.thumb)}">
  <script>window.SLOWDUST_OPEN = ${JSON.stringify(w.slug)};</script>`;

  const html = template
    .replace(META, meta)
    .replace(/<!doctype html>/i, '$&\n<!-- Generated by scripts/build-work-pages.mjs from index.html + work-data.js. Edit those, not this. -->');

  mkdirSync(join(outDir, w.slug), { recursive: true });
  writeFileSync(join(outDir, w.slug, 'index.html'), html);
}

console.log(`Built ${work.length} pages in ${outDir}`);
